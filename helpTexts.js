let data = null;

function load() {
  try {
    if (fs.existsSync(FILE_PATH)) {
      const raw = JSON.parse(fs.readFileSync(FILE_PATH, 'utf8'));
      data = { ...DEFAULTS, ...(raw && typeof raw === 'object' ? raw : {}) };
      return;
    }
  } catch (e) {
    console.warn('[Помощь] Не удалось прочитать help_texts.json, использую тексты по умолчанию:', e.message);
  }
  data = { ...DEFAULTS };
  save();
}

function save() {
  try {
    fs.writeFileSync(FILE_PATH, JSON.stringify(data, null, 2));
  } catch (e) {
    console.warn('[Помощь] Не удалось сохранить help_texts.json:', e.message);
  }
}

function init() {
  load();
}

function getAll() {
  return data;
}

/** Возвращает false, если tabId не из известного набора вкладок. */
function setText(tabId, text) {
  if (!Object.prototype.hasOwnProperty.call(DEFAULTS, tabId)) return false;
  data[tabId] = typeof text === 'string' ? text : '';
  save();
  return true;
}

module.exports = { init, getAll, setText, TAB_IDS: Object.keys(DEFAULTS) };
