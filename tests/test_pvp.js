const { createPvp } = require('../pvp.js'); let ok = 0, bad = 0; const t = (n, c) => { c ? ok++ : (bad++, console.log('FAIL', n)); };
let clock = 1e6; const stage = new Set(['bob', 'carl', 'dan']);
const mk = () => createPvp({ now: () => clock, random: () => 0.37, isOnStage: (l) => stage.has(l), nameOf: (l) => l.toUpperCase() });
let p = mk();
t('не команда → null', p.handle({ login: 'al', message: 'привет' }) === null);
t('без ника → подсказка', /на кого напасть/.test(p.handle({ login: 'al', message: '!пвп' }).reply));
t('на себя нельзя', /самим собой/.test(p.handle({ login: 'bob', message: '!пвп @Bob' }).reply));
t('цели нет на сцене', /нет на сцене/.test(p.handle({ login: 'al', message: '!пвп ghost' }).reply));
const r1 = p.handle({ login: 'al', name: 'Al', message: '!ПВП @Bob' });
t('бой начался', r1.duel && r1.duel.a.login === 'al' && r1.duel.b.login === 'bob' && r1.duel.rounds.length > 0);
t('победитель из двух', [r1.winnerLogin, r1.loserLogin].sort().join() === 'al,bob');
t('тайминги', r1.duel.timing.totalMs > 5000);
t('атакующий занят', /уже в бою/.test(p.handle({ login: 'al', message: '!пвп carl' }).reply));
t('цель занята', /уже дерётся/.test(p.handle({ login: 'carl', message: '!пвп bob' }).reply));
clock += r1.duel.timing.totalMs + 1;
const r2 = p.handle({ login: 'carl', message: '!пвп bob' });
t('на ту же цель — кулдаун 5 мин (даже другой нападающий)', /подожди ещё/.test(r2.reply) && !r2.duel);
clock += 5 * 60 * 1000;
t('через 5 минут можно', !!p.handle({ login: 'carl', message: '!pvp bob' }).duel);
t('другую цель можно сразу', (clock += 20000, !!p.handle({ login: 'al', message: '!пвп dan' }).duel));
p.setEnabled(false); t('выключено → null', p.handle({ login: 'x', message: '!пвп bob' }) === null);
console.log(ok + ' ok, ' + bad + ' fail'); process.exit(bad ? 1 : 0);
